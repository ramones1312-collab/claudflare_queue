/**
 * Every Worker of one environment, in deployment order. `role` drives which secrets it needs.
 * STAGING: receivers -> ingress -> consumers -> admin.  PROD: ingress -> consumers.
 */
export function renderEnv(env, dests, edgeDir) {
  const workers = [];
  if (env === 'staging') {
    for (const d of dests) workers.push({ role: 'receiver', dest: d.id, name: names.receiver(env, d.id), ...renderReceiver(d, edgeDir) });
  }
  workers.push({ role: 'ingress', name: names.ingress(env), ...renderIngress(env, dests, edgeDir) });
  for (const d of dests) workers.push({ role: 'consumer', dest: d.id, name: names.consumer(env, d.id), ...renderConsumer(env, d, edgeDir) });
  if (env === 'staging') workers.push({ role: 'admin', name: names.admin(env), ...renderAdmin(edgeDir) });
  const queues = [];
  for (const d of dests) {
    queues.push({ name: names.queue(env, d.id), kind: 'main', dest: d.id });
    queues.push({ name: names.dlq(env, d.id), kind: 'dlq', dest: d.id });
  }
  const plan = { env, workers, queues };
  assertEnvIsolation(plan);
  return plan;
}

/** Refuse any plan that could let one environment reach the other. Checked on every render. */
export function assertEnvIsolation(plan) {
  const { env } = plan;
  const bad = (msg) => { throw new KawaError('ENV_ISOLATION_VIOLATION', `${env.toUpperCase()} plan refused: ${msg}`); };
  for (const r of [...plan.workers, ...plan.queues]) if (!belongsTo(env, r.name)) bad(`resource ${r.name} does not belong to ${env}`);
  for (const w of plan.workers) {
    const t = w.text;
    if (/integrademia/i.test(t) && env === 'staging') bad(`${w.name} mentions a production hostname`);
    if (/:(8180|8080)\b/.test(t)) bad(`${w.name} names a forbidden control port`);
    if (env === 'prod') {
      if (/\[\[services\]\]/.test(t)) bad(`${w.name} has a Service Binding (staging hard-lock shape)`);
      if (/-stg"|staging-receiver/.test(t)) bad(`${w.name} references a STAGING resource`);
    }
    if (env === 'staging' && w.role === 'consumer') {
      if (!new RegExp(`service = "${names.receiver(env, w.dest)}"`).test(t)) bad(`${w.name} is not hard-locked to its staging receiver`);
      if (/\[secrets\]/.test(t)) bad(`${w.name} declares a webhook secret`);
    }
  }
  return true;
}

export function writeBuild(plan, buildDir) {
  const dir = path.join(buildDir, plan.env);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  for (const w of plan.workers) {
    w.configPath = path.join(dir, `${w.name}.toml`);
    fs.writeFileSync(w.configPath, w.text);
  }
  return dir;
}

/** Digest of the Edge runtime code (ingress + consumer). Binds STAGING evidence to what PROD runs. */
export function edgeSourcesHash(edgeDir) {
  const h = crypto.createHash('sha256');
  for (const f of [...new Set([...SOURCES.ingress, ...SOURCES.consumer])].sort()) {
    h.update(f + '\0'); h.update(fs.readFileSync(path.join(edgeDir, f)));
  }
  return h.digest('hex');
}
