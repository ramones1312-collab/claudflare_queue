/**
 * Wrangler config generation. Replaces every hand-edited TOML: the operator edits ONE json file and
 * the configs are derived from it, deterministically. Same config in -> byte-identical TOML out.
 *
 * Invariants enforced here and re-checked by `assertEnvIsolation()`:
 *   - a STAGING consumer ALWAYS has a Service Binding to its own staging receiver and NO webhook
 *     secret: it is structurally unable to reach any other host (R4 hard-lock, unchanged);
 *   - a PROD config never contains a Service Binding, a staging name or the staging receiver;
 *   - no config ever contains a secret VALUE; secrets are declared in [secrets].required only.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { names, slug, MANAGED_VAR, BUILD_VAR, managedValue, belongsTo } from './naming.mjs';
import { runtimeDestinations } from './config.mjs';
import { KawaError } from './log.mjs';

export const COMPAT_DATE = '2024-12-18';

const q = (s) => JSON.stringify(String(s));            // TOML basic string (JSON escapes are valid TOML)
function lit(s) {                                         // TOML literal string, used for the JSON var
  if (String(s).includes("'") || /[\r\n]/.test(s)) throw new Error('value cannot be a TOML literal string');
  return `'${s}'`;
}

function sha256(buf) { return crypto.createHash('sha256').update(buf).digest('hex'); }

/** Source files that make up each Worker's code, relative to edge/. */
export const SOURCES = {
  ingress: ['src/ingress-entry.js', 'src/producer.js', 'src/sequencer.js', 'src/destinations.js'],
  consumer: ['src/consumer-entry.js', 'src/consumer.js', 'src/destinations.js'],
  receiver: ['staging-receiver/src/index.js'],
  admin: ['admin-worker/src/index.js'],
};

export const MAIN = {
  ingress: 'src/ingress-entry.js',
  consumer: 'src/consumer-entry.js',
  receiver: 'staging-receiver/src/index.js',
  admin: 'admin-worker/src/index.js',
};

/** Build digest = config text (without the digest line) + the exact bytes of the Worker's sources. */
function withBuild(role, text, edgeDir) {
  const h = crypto.createHash('sha256');
  h.update(text);
  for (const f of SOURCES[role]) { h.update('\0' + f + '\0'); h.update(fs.readFileSync(path.join(edgeDir, f))); }
  const digest = h.digest('hex');
  return { text: text.replace('__BUILD__', digest), build: digest };
}

function header(env, role, extra = '') {
  return [
    `# GENERATED by the KAWA Edge deployer — DO NOT EDIT. Source: config/kawa-edge.json`,
    `# Environment: ${env.toUpperCase()} · role: ${role}${extra ? ' · ' + extra : ''}`,
    `# Deployed ONLY with an explicit --config pointing at this file.`,
  ].join('\n');
}

function mainPath(edgeDir, role) { return path.join(edgeDir, MAIN[role]); }

export function renderIngress(env, dests, edgeDir) {
  const lines = [
    header(env, 'ingress + EdgeSequencer Durable Object'),
    `name = ${q(names.ingress(env))}`,
    `main = ${q(mainPath(edgeDir, 'ingress'))}`,
    `compatibility_date = ${q(COMPAT_DATE)}`,
    `workers_dev = true`,
    `preview_urls = false`,
    '',
    '[exports.EdgeSequencer]',
    'type = "durable-object"',
    'storage = "sqlite"',
    '',
    '[[durable_objects.bindings]]',
    'name = "SEQUENCER"',
    'class_name = "EdgeSequencer"',
    '',
    '# NON-SECRET configuration only. The Sequencer is the authority on enabled/disabled.',
    '[vars]',
    `DESTINATIONS = ${lit(JSON.stringify(runtimeDestinations(dests)))}`,
    `${MANAGED_VAR} = ${q(managedValue(env, 'ingress'))}`,
    `${BUILD_VAR} = "__BUILD__"`,
    '',
    '# One queue per destination (enabled or not), so re-enabling never needs a new binding.',
  ];
  for (const d of dests) {
    lines.push('[[queues.producers]]', `queue = ${q(names.queue(env, d.id))}`, `binding = ${q(`DEST_${d.id}_QUEUE`)}`, '');
  }
  lines.push('[secrets]', 'required = ["WEBHOOK_PATH_TOKEN", "HALT_NOTIFY_URL"]', '');
  return withBuild('ingress', lines.join('\n'), edgeDir);
}

export function renderConsumer(env, dest, edgeDir) {
  const id = dest.id;
  const lines = [
    header(env, `delivery consumer for ${id}`),
    `name = ${q(names.consumer(env, id))}`,
    `main = ${q(mainPath(edgeDir, 'consumer'))}`,
    `compatibility_date = ${q(COMPAT_DATE)}`,
    '# A queue consumer needs no HTTP surface at all.',
    `workers_dev = false`,
    `preview_urls = false`,
    '',
    '[[durable_objects.bindings]]',
    'name = "SEQUENCER"',
    'class_name = "EdgeSequencer"',
    `script_name = ${q(names.ingress(env))}`,
    '',
    '[[queues.consumers]]',
    `queue = ${q(names.queue(env, id))}`,
    'max_batch_size = 1',
    'max_batch_timeout = 0',
    '# High: a message waiting its turn retries legitimately (R4). Deliberately NO dead_letter_queue:',
    '# FAILED_PERMANENT means a permanent 4xx from THIS Hub, written by the consumer itself.',
    'max_retries = 100',
    'max_concurrency = 1',
    '',
    '[[queues.producers]]',
    `queue = ${q(names.dlq(env, id))}`,
    `binding = ${q(`DEST_${id}_DLQ`)}`,
    '',
  ];
  if (env === 'staging') {
    lines.push(
      '# STAGING HARD-LOCK: delivery is bound to this destination\'s staging receiver. No other host is reachable.',
      '[[services]]',
      `binding = ${q(`DEST_${id}_FETCHER`)}`,
      `service = ${q(names.receiver(env, id))}`,
      '');
  }
  lines.push(
    '[vars]',
    `CONSUMER_DESTINATION_ID = ${q(id)}`,
    '# Only this destination\'s own entry: the consumer is pinned and never reads another one.',
    `DESTINATIONS = ${lit(JSON.stringify(runtimeDestinations([dest])))}`);
  if (env === 'staging') {
    lines.push('# Not a secret in STAGING: the Service Binding decides the target; this host is never dialled.',
               `DEST_${id}_WEBHOOK_URL = ${q(`https://staging-receiver.invalid/webhook/${slug(id)}-stg`)}`);
  }
  lines.push(`${MANAGED_VAR} = ${q(managedValue(env, `consumer:${id}`))}`, `${BUILD_VAR} = "__BUILD__"`, '');
  if (env === 'prod') {
    lines.push('# PROD: this destination\'s OWN webhook URL (path token included). Bound only here.',
               '[secrets]', `required = [${q(`DEST_${id}_WEBHOOK_URL`)}]`, '');
  }
  return withBuild('consumer', lines.join('\n'), edgeDir);
}

